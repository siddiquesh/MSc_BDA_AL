#Q1
import pandas as pd
import seaborn as sns
from scipy import stats

print("H0: the mean fare paid by male and female passengers differs insignificantly.\nH1:the mean fare paid by male and female passengers differs significantly.")

df = sns.load_dataset("titanic")

male = df[df["sex"] == "male"]["fare"].dropna()
female = df[df["sex"] == "female"]["fare"].dropna()

t_stat, p_value = stats.ttest_ind(
    male, female, equal_var=False
)

print("\nt-statistic:", t_stat)
print("p_value:", p_value)

